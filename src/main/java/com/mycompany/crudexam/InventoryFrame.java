    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText().trim();
        String category = txtCategory.getText().trim();

        if (name.isEmpty() || category.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name and category are required.");
            return;
        }

        int quantity;
        double price;
        try {
            quantity = Integer.parseInt(txtQuantity.getText().trim());
            price = Double.parseDouble(txtPrice.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Quantity must be a whole number and price must be a number.");
            return;
        }

        String sql = "INSERT INTO products ([name], category, quantity, price) VALUES (?, ?, ?, ?)";
        try (Connection conn = MsConnectAccess.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, name);
            ps.setString(2, category);
            ps.setInt(3, quantity);
            ps.setDouble(4, price);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Product added!");
            clearFields();
            loadProducts();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void tblProductsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductsMouseClicked
        // TODO add your handling code here:
        int row = tblProducts.getSelectedRow();
        if (row == -1) {
            return;
        }
        txtName.setText(tblProducts.getValueAt(row, 1).toString());
        txtCategory.setText(tblProducts.getValueAt(row, 2).toString());
        txtQuantity.setText(tblProducts.getValueAt(row, 3).toString());
        txtPrice.setText(tblProducts.getValueAt(row, 4).toString());
    }//GEN-LAST:event_tblProductsMouseClicked

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        int row = tblProducts.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a product from the table first.");
            return;
        }
        int id = (int) tblProducts.getValueAt(row, 0);

        String name = txtName.getText().trim();
        String category = txtCategory.getText().trim();

        if (name.isEmpty() || category.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name and category are required.");
            return;
        }

        int quantity;
        double price;
        try {
            quantity = Integer.parseInt(txtQuantity.getText().trim());
            price = Double.parseDouble(txtPrice.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Quantity must be a whole number and price must be a number.");
            return;
        }

        String sql = "UPDATE products SET [name] = ?, category = ?, quantity = ?, price = ? WHERE id = ?";
        try (Connection conn = MsConnectAccess.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, name);
            ps.setString(2, category);
            ps.setInt(3, quantity);
            ps.setDouble(4, price);
            ps.setInt(5, id);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Product updated!");
            clearFields();
            loadProducts();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int row = tblProducts.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a product from the table first.");
            return;
        }

        int id = (int) tblProducts.getValueAt(row, 0);
        String name = tblProducts.getValueAt(row, 1).toString();

        int confirm = JOptionPane.showConfirmDialog(this,
                "Delete \"" + name + "\"? This cannot be undone.",
                "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM products WHERE id = ?";
        try (Connection conn = MsConnectAccess.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setInt(1, id);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Product deleted!");
            clearFields();
            loadProducts();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

